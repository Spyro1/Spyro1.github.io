/** Decorative dot grid from the original site. */
export function Dots({ className, rows = 5 }: { className?: string; rows?: number }) {
  const size = rows * 24 - 16;
  return (
    <svg
      viewBox={`0 0 ${size} ${size}`}
      aria-hidden="true"
      className={cn("fill-gray", className)}
    >
      {Array.from({ length: rows * rows }, (_, i) => (
        <circle key={i} cx={4 + (i % rows) * 24} cy={4 + Math.floor(i / rows) * 24} r={4} />
      ))}
    </svg>
  );
}
